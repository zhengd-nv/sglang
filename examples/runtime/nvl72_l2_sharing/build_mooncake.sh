#!/usr/bin/env bash
# Build Mooncake with EGM support and the NVLink grouped-scatter fix, and
# assemble a Python overlay that shadows the mooncake package shipped in the
# SGLang image. Run inside the same container you will serve with.
#
#   WORK=/shared/l2-sharing ./build_mooncake.sh
#
# Produces $WORK/build (CMake tree), $WORK/py (overlay package) and
# $WORK/env.sh, which the other scripts source.
#
# Optional:
#   MOONCAKE_SRC   existing checkout to build instead of cloning
#   DEPS_PREFIX    prefix holding yaml-cpp, zstd, xxHash and msgpack-c when
#                  the image lacks them (Mooncake's dependencies.sh installs
#                  them system-wide instead)
#   BUILD_JOBS     parallel compile jobs (default: nproc)
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
: "${WORK:?set WORK to a directory visible from every node}"
MOONCAKE_REPO="${MOONCAKE_REPO:-https://github.com/kvcache-ai/Mooncake.git}"
# Mooncake main with the EGM store pool (PRs #2966, #3335, #3431); the
# 0.3.13.post1 wheel in the SGLang image predates them.
MOONCAKE_COMMIT="${MOONCAKE_COMMIT:-522b716ee7ba459008b59fd6fa3c6937fcde93c9}"
PATCH="$HERE/mooncake-nvlink-grouped-scatter.patch"
mkdir -p "$WORK"

if [[ -z "${MOONCAKE_SRC:-}" ]]; then
  MOONCAKE_SRC="$WORK/src"
  if [[ ! -d "$MOONCAKE_SRC/.git" ]]; then
    git clone --filter=blob:none "$MOONCAKE_REPO" "$MOONCAKE_SRC"
  fi
  git -C "$MOONCAKE_SRC" checkout --detach "$MOONCAKE_COMMIT"
  git -C "$MOONCAKE_SRC" submodule update --init extern/pybind11
fi

if git -C "$MOONCAKE_SRC" apply --reverse --check "$PATCH" 2>/dev/null; then
  echo "grouped-scatter patch already applied"
else
  git -C "$MOONCAKE_SRC" apply "$PATCH"
fi

CMAKE_EXTRA=()
if [[ -n "${DEPS_PREFIX:-}" ]]; then
  CMAKE_EXTRA+=(-DCMAKE_PREFIX_PATH="$DEPS_PREFIX")
  # mooncake_common includes yaml-cpp headers without linking the target.
  export CPATH="$DEPS_PREFIX/include${CPATH:+:$CPATH}"
  export LIBRARY_PATH="$DEPS_PREFIX/lib${LIBRARY_PATH:+:$LIBRARY_PATH}"
fi

BUILD="$WORK/build"
cmake -S "$MOONCAKE_SRC" -B "$BUILD" -G Ninja -DCMAKE_BUILD_TYPE=Release \
  -DUSE_CUDA=ON -DUSE_MNNVL=ON -DWITH_TE=ON -DWITH_STORE=ON \
  -DUSE_TENT=OFF -DWITH_STORE_RUST=OFF -DWITH_EP=OFF \
  -DBUILD_UNIT_TESTS=OFF -DBUILD_EXAMPLES=OFF -DBUILD_BENCHMARK=OFF "${CMAKE_EXTRA[@]}"
cmake --build "$BUILD" --parallel "${BUILD_JOBS:-$(nproc)}" --target mooncake_master store

# Overlay: the upstream mooncake/__init__.py uses pkgutil.extend_path, so
# modules missing here still resolve from the image's installed package.
PY="$WORK/py"
rm -rf "$PY"; mkdir -p "$PY"
cp -r "$MOONCAKE_SRC/python/mooncake" "$PY/mooncake"
cp "$BUILD"/mooncake-integration/_store*.so "$PY/mooncake/"
cp "$BUILD/mooncake-common/libasio.so" "$PY/mooncake/"
find "$PY/mooncake" -name __pycache__ -prune -exec rm -rf {} +

LIBS="$BUILD/mooncake-common:$BUILD/mooncake-transfer-engine/src"
[[ -z "${DEPS_PREFIX:-}" ]] || LIBS="$DEPS_PREFIX/lib:$LIBS"
cat > "$WORK/env.sh" <<EOF
# Generated by build_mooncake.sh from Mooncake $(git -C "$MOONCAKE_SRC" rev-parse HEAD) + grouped-scatter patch.
export MOONCAKE_MASTER_BIN="$BUILD/mooncake-store/src/mooncake_master"
export PYTHONPATH="$PY\${PYTHONPATH:+:\$PYTHONPATH}"
export LD_LIBRARY_PATH="$LIBS\${LD_LIBRARY_PATH:+:\$LD_LIBRARY_PATH}"
# Pick NVLink explicitly instead of auto-discovering a transport.
export MC_MS_AUTO_DISC=0
unset MC_FORCE_MNNVL MC_USE_TENT MC_USE_TEV1
EOF
echo "Wrote $WORK/env.sh"
